package com.Scalar;

public class unboxing {
    public static void main(String[] args) {
        Integer inta = 3;
        Float floatb = 4.5f;
        Long longc = 59598789876L;
        Character chard = 'i';

        //unboxing
        int a = inta;
        float b = floatb;
        long c = longc;
        char d = chard;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);

    }
}
